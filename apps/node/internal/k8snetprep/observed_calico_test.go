// The Calico rules in this file are MODELLED on the masquerade rule Calico
// documents for its iptables dataplane ("natOutgoing"): source in the masq
// pools set, destination not in the all-pools set, MASQUERADE. They were not
// captured from a live Calico node. The nft form assumes what iptables-nft
// produces for the other fixtures in this package: `-m set` and the MASQUERADE
// target as typed xt descriptors. A real node (Calico v3.31.2) printed exactly
// this rule; its captures and the tests on them are in
// observed_calico_live_linux_test.go. These modelled rules stay for the
// mutations, which need rules a real node does not have.

const (
	xtSet        = `{"xt":{"type":"match","name":"set"}}`
	calicoMasq   = "cali40masq-ipam-pools"
	calicoAll    = "cali40all-ipam-pools"
	calicoMasqOK = "-m set --match-set " + calicoMasq + " src -m set ! --match-set " + calicoAll + " dst"
)

func calicoNFT() map[string][]string {
	return map[string][]string{
		"POSTROUTING": {
			`[` + xtComment + `,{"jump":{"target":"cali-POSTROUTING"}}]`,
			`[` + xtComment + `,{"jump":{"target":"KUBE-POSTROUTING"}}]`,
		},
		"cali-POSTROUTING": {
			`[` + xtComment + `,{"jump":{"target":"cali-nat-outgoing"}}]`,
		},
		"cali-nat-outgoing": {
			`[` + xtComment + `,` + xtSet + `,` + xtSet + `,` + xtMasquerade + `]`,
		},
		"KUBE-POSTROUTING": {
			`[` + kubeUnmarked + `,` + returnVerdict + `]`,
			`[` + xtMark + `]`,
			`[` + xtComment + `,` + xtMasquerade + `]`,
		},
	}
}

// calicoSave is the iptables-nft-save text for calicoNFT. outgoing replaces the
// rules of cali-nat-outgoing, each given without its `-A chain` prefix.
func calicoSave(outgoing ...string) string {
	lines := []string{
		"# Generated by iptables-nft-save v1.8.10 (nf_tables)",
		"*nat",
		":PREROUTING ACCEPT [0:0]",
		":POSTROUTING ACCEPT [0:0]",
		":KUBE-POSTROUTING - [0:0]",
		":cali-POSTROUTING - [0:0]",
		":cali-nat-outgoing - [0:0]",
		`-A POSTROUTING -m comment --comment "cali:O3lYWMrLQYEMJtB5" -j cali-POSTROUTING`,
		`-A POSTROUTING -m comment --comment "kubernetes postrouting rules" -j KUBE-POSTROUTING`,
		"-A KUBE-POSTROUTING -m mark ! --mark 0x4000/0x4000 -j RETURN",
		"-A KUBE-POSTROUTING -j MARK --set-xmark 0x4000/0x0",
		`-A KUBE-POSTROUTING -m comment --comment "kubernetes service traffic requiring SNAT" -j MASQUERADE --random-fully`,
		`-A cali-POSTROUTING -m comment --comment "cali:Z-c7XtVd2Bq7s_hA" -j cali-nat-outgoing`,
	}
	for _, rule := range outgoing {
		lines = append(lines, "-A cali-nat-outgoing "+rule)
	}
	return strings.Join(append(lines, "COMMIT", "# Completed on Mon Nov 23 00:00:00 2026"), "\n") + "\n"
}

func calicoOutgoing(sets string) string {
	return `-m comment --comment "cali:flqWnvo8yq4ULQLa" ` + sets + ` -j MASQUERADE --random-fully`
}

func calicoFacts(t *testing.T, save string, members map[string][]string) *natSetFacts {
	t.Helper()
	saved, err := parseSavedRules(save)
	if err != nil {
		t.Fatal(err)
	}
	facts := &natSetFacts{saved: saved, members: map[string][]netip.Prefix{}}
	for name, list := range members {
		facts.members[name] = []netip.Prefix{}
		for _, member := range list {
			facts.members[name] = append(facts.members[name], netip.MustParsePrefix(member))
		}
	}
	return facts
}

var calicoTunnel = netip.MustParsePrefix("100.96.0.0/24")

func TestObservedAcceptsCalicoMasqueradeLimitedToPodPools(t *testing.T) {
	chains, rules := observedRules(t, calicoNFT())
	save := calicoSave(calicoOutgoing(calicoMasqOK))

	// Without the saved text and the set, the rule stays refused, and the
	// refusal says that set facts are what is missing.
	if err := proveNoTunnelSourceNAT(chains, rules, "POSTROUTING", calicoTunnel, nil); !errors.Is(err, errSetFactsNeeded) {
		t.Fatalf("masquerade behind unread sets: %v", err)
	}

	// Only the set that can carry the proof is asked for: the negated
	// destination set narrows the rule and is never read.
	facts := calicoFacts(t, save, nil)
	needed, err := setsNeededForProof(chains, rules, "POSTROUTING", calicoTunnel, "", nil, facts.saved)
	if err != nil || !reflect.DeepEqual(needed, []string{calicoMasq}) {
		t.Fatalf("sets needed = %v, %v", needed, err)
	}

	facts = calicoFacts(t, save, map[string][]string{calicoMasq: {"192.168.0.0/16", "10.42.0.0/16"}})
	proof, err := proveNoTunnelSourceNATWithSets(chains, rules, "POSTROUTING", calicoTunnel, "", nil, facts)
	if err != nil || !reflect.DeepEqual(proof, []string{calicoMasq}) {
		t.Fatalf("Calico rules were refused: %v %v", proof, err)
	}
	if reason := observedReadyReason(proof); !strings.HasPrefix(reason, ReasonObservedNoTunnelSourceNAT) || !strings.HasSuffix(reason, ": "+calicoMasq) {
		t.Fatalf("reason = %q", reason)
	}
}

func TestObservedRefusesCalicoRulesThatProveNothing(t *testing.T) {
	pods := map[string][]string{calicoMasq: {"192.168.0.0/16"}, calicoAll: {"192.168.0.0/16"}}
	twoRuleNFT := func() map[string][]string {
		nft := calicoNFT()
		nft["cali-nat-outgoing"] = []string{
			`[` + xtSet + `,` + returnVerdict + `]`,
			`[` + xtComment + `,` + xtSet + `,` + xtMasquerade + `]`,
		}
		return nft
	}
	for name, tc := range map[string]struct {
		nft     map[string][]string
		save    string
		members map[string][]string
		want    string
	}{
		"pool overlaps the tunnel range": {
			calicoNFT(), calicoSave(calicoOutgoing(calicoMasqOK)),
			map[string][]string{calicoMasq: {"192.168.0.0/16", "100.64.0.0/10"}},
			"set " + calicoMasq + ", which overlaps the tunnel range 100.96.0.0/24",
		},
		"pool is everything": {
			calicoNFT(), calicoSave(calicoOutgoing(calicoMasqOK)),
			map[string][]string{calicoMasq: {"0.0.0.0/0"}}, "overlaps",
		},
		"negated source match": {
			calicoNFT(), calicoSave(calicoOutgoing("-m set ! --match-set " + calicoMasq + " src -m set ! --match-set " + calicoAll + " dst")),
			pods, "can rewrite the source",
		},
		"destination-only match": {
			calicoNFT(), calicoSave(calicoOutgoing("-m set --match-set " + calicoMasq + " dst -m set ! --match-set " + calicoAll + " dst")),
			pods, "can rewrite the source",
		},
		"source,destination pair match": {
			calicoNFT(), calicoSave(calicoOutgoing("-m set --match-set " + calicoMasq + " src,dst -m set ! --match-set " + calicoAll + " dst")),
			pods, "can rewrite the source",
		},
		"missing set": {
			calicoNFT(), calicoSave(calicoOutgoing(calicoMasqOK)),
			map[string][]string{calicoAll: {"192.168.0.0/16"}}, "set " + calicoMasq + ", which was not read",
		},
		"saved text has no such chain": {
			calicoNFT(), strings.ReplaceAll(calicoSave(calicoOutgoing(calicoMasqOK)), "-A cali-nat-outgoing ", "-A cali-other "),
			pods, "cannot be read",
		},
		"saved text has one rule more": {
			calicoNFT(), calicoSave(calicoOutgoing(calicoMasqOK), "-j RETURN"),
			pods, "cannot be read",
		},
		"saved text has one set match fewer": {
			calicoNFT(), calicoSave(calicoOutgoing("-m set --match-set " + calicoMasq + " src")),
			pods, "does not pair",
		},
		"saved text ends in another target": {
			calicoNFT(), calicoSave(`-m comment --comment "cali:flqWnvo8yq4ULQLa" ` + calicoMasqOK + ` -j RETURN`),
			pods, "does not pair",
		},
		// nft: [set -> RETURN], [set -> MASQUERADE]. The saved text lists the
		// same two rules the other way round, as it would if the chain were
		// rewritten between the two readings.
		"rule order differs between the readings": {
			twoRuleNFT(), calicoSave(
				`-m comment --comment "cali:flqWnvo8yq4ULQLa" -m set --match-set `+calicoMasq+` src -j MASQUERADE --random-fully`,
				`-m set --match-set `+calicoAll+` dst -j RETURN`),
			pods, "rule 1 does not pair",
		},
	} {
		chains, rules := observedRules(t, tc.nft)
		facts := calicoFacts(t, tc.save, tc.members)
		proof, err := proveNoTunnelSourceNATWithSets(chains, rules, "POSTROUTING", calicoTunnel, "", nil, facts)
		if err == nil || !strings.Contains(err.Error(), tc.want) {
			t.Errorf("%s: proof %v, error %v", name, proof, err)
		}
		if errors.Is(err, errSetFactsNeeded) {
			t.Errorf("%s: asks for set facts again: %v", name, err)
		}
	}
}

// The same two rules in the same order in both readings are accepted, so the
// order refusal above is about order and not about the two-rule chain.
func TestObservedPairsRulesByPosition(t *testing.T) {
	nft := calicoNFT()
	nft["cali-nat-outgoing"] = []string{
		`[` + xtSet + `,` + returnVerdict + `]`,
		`[` + xtComment + `,` + xtSet + `,` + xtMasquerade + `]`,
	}
	chains, rules := observedRules(t, nft)
	facts := calicoFacts(t, calicoSave(
		`-m set --match-set `+calicoAll+` dst -j RETURN`,
		`-m comment --comment "cali:flqWnvo8yq4ULQLa" -m set --match-set `+calicoMasq+` src -j MASQUERADE --random-fully`),
		map[string][]string{calicoMasq: {"192.168.0.0/16"}})
	proof, err := proveNoTunnelSourceNATWithSets(chains, rules, "POSTROUTING", calicoTunnel, "", nil, facts)
	if err != nil || !reflect.DeepEqual(proof, []string{calicoMasq}) {
		t.Fatalf("paired chain was refused: %v %v", proof, err)
	}
}

// Set facts widen nothing else: a masquerade with no set match, and one whose
// only condition is another opaque extension, stay refused with facts present.
func TestObservedSetFactsDoNotExcuseOtherMasquerades(t *testing.T) {
	for name, rule := range map[string]string{
		"unguarded":          `[` + xtMasquerade + `]`,
		"behind an addrtype": `[` + xtAddrtype + `,` + xtMasquerade + `]`,
	} {
		nft := calicoNFT()
		nft["cali-nat-outgoing"] = append(nft["cali-nat-outgoing"], rule)
		chains, rules := observedRules(t, nft)
		facts := calicoFacts(t, calicoSave(calicoOutgoing(calicoMasqOK), "-j MASQUERADE"), map[string][]string{calicoMasq: {"192.168.0.0/16"}})
		if _, err := proveNoTunnelSourceNATWithSets(chains, rules, "POSTROUTING", calicoTunnel, "", nil, facts); err == nil {
			t.Errorf("%s: accepted", name)
		}
	}
}

func TestSetsNeededForProofIsBounded(t *testing.T) {
	nft := map[string][]string{"POSTROUTING": {}}
	save := []string{"*nat", ":POSTROUTING ACCEPT [0:0]"}
	for i := 0; i <= maxProofSets; i++ {
		nft["POSTROUTING"] = append(nft["POSTROUTING"], `[`+xtSet+`,`+xtMasquerade+`]`)
		save = append(save, "-A POSTROUTING -m set --match-set pool"+string(rune('a'+i))+" src -j MASQUERADE")
	}
	chains, rules := observedRules(t, nft)
	saved, err := parseSavedRules(strings.Join(append(save, "COMMIT"), "\n"))
	if err != nil {
		t.Fatal(err)
	}
	if _, err := setsNeededForProof(chains, rules, "POSTROUTING", calicoTunnel, "", nil, saved); err == nil {
		t.Fatal("unbounded set reads were accepted")
	}
}

func TestParseSavedRulesReadsTargetsAndRefusesUnsafeSetNames(t *testing.T) {
	saved, err := parseSavedRules(calicoSave(calicoOutgoing(calicoMasqOK)))
	if err != nil {
		t.Fatal(err)
	}
	if got := saved["cali-nat-outgoing"]; len(got) != 1 || got[0].Target != "MASQUERADE" || len(got[0].Sets) != 2 {
		t.Fatalf("cali-nat-outgoing = %+v", got)
	}
	if got := saved["KUBE-POSTROUTING"]; len(got) != 3 || got[0].Target != "RETURN" || got[1].Target != "MARK" || len(got[0].Sets) != 0 {
		t.Fatalf("KUBE-POSTROUTING = %+v", got)
	}
	for _, name := range []string{"a;b", "a/b", "$(x)", "-f", "a-b", strings.Repeat("x", 31)} {
		_, err := parseSavedRules("-A c -m set --match-set " + name + " src -j MASQUERADE")
		if valid := name == "a-b" || len(name) == 31; (err == nil) != valid {
			t.Errorf("set name %q: %v", name, err)
		}
	}
}

func TestObservedReadyReasonIsBounded(t *testing.T) {
	if got := observedReadyReason(nil); got != ReasonObservedNoTunnelSourceNAT {
		t.Fatalf("reason without sets = %q", got)
	}
	var names []string
	for i := 0; i < 12; i++ {
		names = append(names, strings.Repeat(string(rune('a'+i)), 31))
	}
	got := observedReadyReason(names)
	if len(got) > maxReasonBytes || !strings.Contains(got, names[0]) || !strings.HasSuffix(got, "and 9 more") {
		t.Fatalf("reason (%d bytes) = %q", len(got), got)
	}
}


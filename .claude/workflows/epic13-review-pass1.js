phase('Find')

const perFinder = await pipeline(
  FINDERS,
  (f) => agent(f.prompt, { label: `find:${f.key}`, phase: 'Find', schema: FINDING_SCHEMA })
    .then((r) => ({ key: f.key, findings: (r && r.findings) || [] })),
  (r) => {
    if (!r || !r.findings.length) return { key: r ? r.key : 'unknown', verified: [] }
    const rank = { CRITICAL: 0, HIGH: 1, MEDIUM: 2, LOW: 3 }
    const ordered = r.findings.slice().sort((a, b) => rank[a.severity] - rank[b.severity])
    const take = ordered.slice(0, 6)
    if (ordered.length > take.length) {
      log(`CAP: ${r.key} reported ${ordered.length} findings; verifying the top ${take.length} by severity. Dropped: ${ordered.slice(6).map(f => f.title).join(' | ')}`)
    }
    return parallel(take.map((f) => () =>
      parallel([
        () => agent(`${SCOPE}

You are REFUTING a review finding. Default to refuted=true unless you can confirm the failing sequence by READING
THE CODE. Verify by construction, not by plausibility.

LENS: CORRECTNESS. Does the described sequence actually occur? Read every function on the path and check whether
some guard, type, SQL clause, transaction boundary or caller precondition already prevents it. Quote the lines
that decide it. If the finding is directionally right but the mechanism is wrong, set refuted=false and give the
CORRECTION.

FINDING
title: ${f.title}
file: ${f.file}:${f.line}
severity: ${f.severity}
sequence: ${f.failure_sequence}
why: ${f.why_it_matters}`, { label: `verify:correct:${f.title.slice(0, 28)}`, phase: 'Verify', schema: VERDICT_SCHEMA }),
        () => agent(`${SCOPE}

You are REFUTING a review finding. Default to refuted=true unless you can confirm it by reading the code.

LENS: EXPLOITABILITY AND REACHABILITY. Assume the described mechanism is real. Can an UNAUTHENTICATED remote
caller actually reach it, and what do they gain? Work out: what must they know beforehand (a real serial? a real
fingerprint? a private key?), how many requests it takes, whether the throttle or the body cap or the gone-gate
stops them first, and whether the outcome is a security consequence or merely an internal error. A defect that
requires already holding the node's private key, or database access, is NOT the finding it claims to be — say so.
Also state whether an EXISTING test would have caught it (name the test).

FINDING
title: ${f.title}
file: ${f.file}:${f.line}
severity: ${f.severity}
sequence: ${f.failure_sequence}
why: ${f.why_it_matters}`, { label: `verify:exploit:${f.title.slice(0, 28)}`, phase: 'Verify', schema: VERDICT_SCHEMA }),
      ]).then((vs) => {
        const votes = (vs || []).filter(Boolean)
        const refuted = votes.filter((v) => v.refuted).length
        return {
          ...f,
          finder: r.key,
          survived: votes.length > 0 && refuted < votes.length,
          unanimous_survive: votes.length > 0 && refuted === 0,
          verdicts: votes,
        }
      })
    )).then((verified) => ({ key: r.key, verified: (verified || []).filter(Boolean) }))
  }
)

const all = perFinder.filter(Boolean).flatMap((r) => r.verified || [])
const survivors = all.filter((f) => f.survived)
log(`${all.length} findings verified; ${survivors.length} survived at least one lens (${all.filter(f => f.unanimous_survive).length} unanimous).`)

